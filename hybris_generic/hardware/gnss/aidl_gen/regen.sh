# Regenerate the libbinder_ndk AIDL client/server code for the Android
# GNSS HAL, version 3 — the version the Halium 14 container's
# android.hardware.gnss-service.mediatek publishes on this device
# (/android/vendor/etc/vintf/manifest/gnss-default.xml, and the HAL links
# android.hardware.gnss-V3-ndk.so).
#
# The generated tree is CHECKED IN so the OHOS build needs neither the
# `aidl` compiler nor an AOSP checkout.  Re-run this only to move to a
# different frozen version.
#
# Inputs (fetched, not vendored):
#   AIDL       path to AOSP's aidl compiler (Android SDK build-tools >= 34,
#              e.g. build-tools_r34-linux.zip -> android-14/aidl)
#   AOSP_GNSS  path to an export of
#              platform/hardware/interfaces/gnss/aidl/aidl_api
#              (android14-release), e.g. the gitiles tarball
#              .../+archive/refs/heads/android14-release/gnss/aidl/aidl_api.tar.gz
#
# Usage:
#   AIDL=~/build-tools/android-14/aidl AOSP_GNSS=~/aidl_api ./regen.sh
#
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AIDL="${AIDL:?set AIDL=<path to aidl compiler>}"
AOSP_GNSS="${AOSP_GNSS:?set AOSP_GNSS=<path to gnss/aidl/aidl_api>}"
VERSION=3
SNAP="$AOSP_GNSS/android.hardware.gnss/$VERSION"

[ -d "$SNAP" ] || { echo "missing $SNAP" >&2; exit 1; }

rm -rf "$HERE/src" "$HERE/include"
mkdir -p "$HERE/src" "$HERE/include"

# One package, one version: measurement_corrections and visibility_control
# are sub-packages frozen inside the android.hardware.gnss snapshot, not
# separate interfaces.  --stability=vintf matches @VintfStability; without
# it the HAL rejects our callback binders.
mapfile -t SRCS < <(find "$SNAP" -name '*.aidl' | sort)
"$AIDL" --lang=ndk --structured --stability=vintf \
        --version="$VERSION" --min_sdk_version=31 \
        -I "$SNAP" \
        --out="$HERE/src" --header_out="$HERE/include" \
        "${SRCS[@]}"

# GN cannot glob, so publish the file list the build imports.
{
    cat <<'HDR'
# Copyright (c) 2026 Eclipse Oniro for OpenHarmony contributors.
# SPDX-License-Identifier: Apache-2.0
#
# GENERATED by regen.sh — do not edit.

gnss_aidl_sources = [
HDR
    (cd "$HERE" && find src -name '*.cpp' | sort | sed 's|^|  "aidl_gen/|; s|$|",|')
    echo "]"
} > "$HERE/sources.gni"

echo "generated $(find "$HERE/src" -name '*.cpp' | wc -l) sources, \
$(find "$HERE/include" -name '*.h' | wc -l) headers, sources.gni"
